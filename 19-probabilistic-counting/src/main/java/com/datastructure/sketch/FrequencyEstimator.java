package com.datastructure.sketch;

/**
 * "이 원소가 몇 번 나왔나" 에 답한다.
 *
 * 11번 블룸 필터는 "있나 없나"였다. 여기서 한 걸음 더 간다.
 *
 * 정확히 세려면 원소마다 칸이 하나씩 있어야 한다.
 * 서로 다른 것이 1억 개면 해시맵 엔트리가 1억 개다. 수 GB 다.
 * 그런데 대부분의 원소는 한두 번 나오고 끝난다. 우리가 궁금한 것은 많이 나온 소수다.
 *
 * Count-Min 스케치는 칸 수를 미리 고정한다. 원소가 몇 종류든 상관없다.
 * 대신 충돌이 생기고, 충돌은 한 방향으로만 틀린다.
 *
 *   추정치 >= 실제                절대 과소평가하지 않는다
 *   추정치 <= 실제 + (오차율 x 전체 개수)   확률 (1 - delta) 로
 *
 * 11번의 비대칭("없다는 확실, 있다는 아마")과 같은 모양이다.
 * 한쪽 방향으로만 틀리는 것이 쓸모의 전부다. 상한을 알면 판단할 수 있다.
 *
 * | | 정확한 계수기(HashMap) | Count-Min 스케치 |
 * |---|---|---|
 * | 메모리 | 서로 다른 원소 수에 비례 | 고정 |
 * | 1억 종류 | 수 GB | 수 MB |
 * | 오차 | 없다 | 위로만 |
 * | 원소를 되찾기 | 된다 | 안 된다 |
 *
 * 실제 쓰임: 네트워크 트래픽의 heavy hitter 탐지, 검색어 순위, 광고 노출 집계,
 * 데이터베이스 쿼리 최적화기의 선택도 추정.
 *
 * 이 인터페이스에는 TODO 가 없다. 계약은 주어지는 것이다.
 */
public interface FrequencyEstimator {

    /** 한 번 봤다. */
    void add(int item);

    /** count 번 봤다. count 는 0 이상이어야 한다. */
    void add(int item, long count);

    /** 몇 번 나왔나. 실제보다 작을 수는 없다. */
    long estimateCount(int item);

    /** 지금까지 더한 전체 개수(중복 포함). 오차 한계를 계산할 때 쓴다. */
    long totalCount();

    /** 저장에 쓰는 대략의 바이트 수. */
    long memoryBytes();
}
