package com.datastructure.sketch;

/**
 * "서로 다른 것이 몇 개인가" 에 답한다.
 *
 * 빈도(FrequencyEstimator)와 다른 질문이다.
 * "방문자 수"가 아니라 "순 방문자 수", 조회수가 아니라 유니크 사용자 수.
 *
 * 정확히 세려면 본 것을 전부 기억해야 한다. HashSet 이 그렇게 한다.
 * 1억 개면 수 GB 다. 그리고 원소를 다시 볼 일이 없는데도 계속 들고 있어야 한다.
 *
 * HyperLogLog 는 원소를 안 담는다. 해시의 모양만 기억한다.
 *
 * 발상이 이렇다. 무작위 비트열을 여러 개 보다가 "앞에 0이 17개 연달아 나온 것"을 봤다면,
 * 대략 2^17 개쯤 봤을 가능성이 높다. 가장 희귀한 사건이 표본 크기를 말해준다.
 *
 * 그 추정은 흔들림이 크므로 레지스터 m 개로 나눠 각각 재고 조화평균을 낸다.
 * 표준 오차가 1.04/sqrt(m) 이 된다. m = 16384 면 0.81% 다.
 *
 * | | HashSet | HyperLogLog (m=16384) |
 * |---|---|---|
 * | 1억 개 카디널리티 | 수 GB | 12KB |
 * | 오차 | 없다 | 약 0.8% |
 * | 합집합 | 두 집합을 다 훑는다 | 레지스터 max 만. O(m) |
 * | 교집합 | 된다 | 포함배제로 흉내만 (오차가 커진다) |
 *
 * 세 번째 줄이 실무에서 결정적이다. 서버 100대가 각자 12KB 를 보내면
 * 원본을 하나도 안 보내고 전체 순 방문자를 안다.
 * 레디스의 PFADD/PFCOUNT/PFMERGE, 구글 BigQuery 의 APPROX_COUNT_DISTINCT 가 이것이다.
 *
 * 이 인터페이스에는 TODO 가 없다. 계약은 주어지는 것이다.
 */
public interface CardinalityEstimator {

    void add(int item);

    /** 서로 다른 원소가 몇 개였나. */
    long estimate();

    /** 저장에 쓰는 대략의 바이트 수. */
    long memoryBytes();
}
