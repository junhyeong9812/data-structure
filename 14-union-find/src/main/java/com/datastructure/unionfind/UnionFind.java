package com.datastructure.unionfind;

/**
 * 원소들을 묶음으로 관리한다. **합치기만 하고 쪼개지 않는다.**
 *
 * 08번 그래프에서 "이 둘이 연결돼 있나"는 BFS 로 O(V + E) 에 답했다.
 * 그런데 간선이 **하나씩 들어오는** 상황이라면 매번 다시 돌려야 한다.
 * 간선 m 개를 넣으며 계속 물으면 O(m(V + E)) 다.
 *
 * 유니온 파인드는 그 질문에 **증분적으로** 답한다. 간선 하나가 들어오면 그것만 반영한다.
 * 그리고 그 값이 거의 O(1) 이다.
 *
 * | | 연결 여부 | 간선 추가 | 경로 |
 * |---|---|---|---|
 * | BFS/DFS (08번) | O(V + E) 매번 | O(1) | **알려준다** |
 * | 유니온 파인드 | **거의 O(1)** | 거의 O(1) | 모른다 |
 *
 * 마지막 열이 대가다. **"연결돼 있다"만 알고 "어떻게"는 모른다.**
 * 그리고 **한 번 합친 것은 쪼갤 수 없다.** 이 둘을 포기하고 속도를 얻는다.
 *
 * 얼마나 빠른가. 두 최적화를 다 넣으면 연산당 **역아커만 함수 a(n)** 이 되는데,
 * 우주의 원자 수보다 큰 n 에서도 4 를 안 넘는다. 사실상 상수다.
 *
 *   1. **크기로 붙이기** - 작은 나무를 큰 나무 밑에 붙인다. 깊이가 log n 을 안 넘는다
 *   2. **경로 압축** - find 하면서 지나온 노드를 전부 뿌리에 직접 붙인다
 *
 * 2번이 중요하다. **조회가 자료구조를 바꾼다.** 10번 LRU 의 get, 13번 lazy 의 rangeSum 과 같다.
 * 그리고 바로 그 때문에 쪼갤 수 없다. **압축이 "원래 누구 밑이었는지"를 지우기 때문이다.**
 *
 * 정점은 0 부터 size-1 까지의 정수다(08번과 같은 단순화).
 * 정수가 아닌 것을 다루려면 DisjointSet 을 쓴다.
 *
 * 이 인터페이스에는 TODO 가 없다. 계약은 주어지는 것이다.
 */
public interface UnionFind {

    /** x 가 속한 묶음의 대표. 같은 묶음이면 같은 대표가 나온다. */
    int find(int x);

    /** 합친다. 원래 다른 묶음이었으면 true, 이미 같았으면 false. */
    boolean union(int x, int y);

    boolean connected(int x, int y);

    /** 지금 묶음이 몇 개인가. 처음엔 원소 수와 같고 합칠 때마다 하나씩 준다. */
    int componentCount();

    /** 전체 원소 수. */
    int size();

    /** x 가 속한 묶음의 크기. */
    int sizeOf(int x);
}
