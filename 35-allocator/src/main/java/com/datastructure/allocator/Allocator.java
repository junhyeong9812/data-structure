package com.datastructure.allocator;

/**
 * 고정된 크기의 공간에서 자리를 떼어주고 돌려받는 것의 계약.
 *
 * 앞의 자료구조들은 필요할 때마다 new 를 썼다. 그 new 가 하는 일이 이것이다.
 *
 * <h2>주소를 준다</h2>
 *
 * allocate 는 시작 위치를 준다. 자리가 없으면 FAIL 이다. 예외가 아니다.
 * 자리가 없는 것은 오류가 아니라 정상적인 결과이기 때문이다.
 * malloc 이 null 을 주는 것과 같다.
 *
 * <h2>재는 것이 이 박스의 내용이다</h2>
 *
 * 자리를 떼어주는 코드는 짧다. 어려운 것은 <b>어디를 떼어줄지</b>이고,
 * 그 선택의 결과는 한참 뒤에 "빈 공간은 많은데 할당이 실패한다" 로 나타난다.
 *
 * <pre>
 *   freeBytes         남은 공간의 총합
 *   largestFreeBlock  그중 연속된 가장 큰 덩어리
 *
 *   이 둘이 벌어진 정도가 외부 단편화다. 1000 바이트가 남았는데
 *   가장 큰 덩어리가 8 바이트면 9 바이트 요청이 실패한다.
 * </pre>
 *
 * 이 인터페이스에는 TODO 가 없다.
 */
public interface Allocator {

    /** 자리가 없을 때 주는 값. 음수라 주소와 섞이지 않는다. */
    int FAIL = -1;

    /**
     * size 바이트를 떼어주고 시작 주소를 준다. 없으면 FAIL.
     *
     * size 가 0 이하이면 던진다. 0 바이트 할당을 허용하면 free 가
     * 무엇을 돌려받아야 하는지 정할 수 없다.
     */
    int allocate(int size);

    /**
     * 이 주소에서 시작하는 자리를 돌려받는다.
     *
     * 준 적 없는 주소나 이미 돌려받은 주소를 주면 던진다.
     * 조용히 넘어가면 같은 자리를 두 번 세어 남은 공간이 부풀고,
     * 그 뒤로는 없는 자리를 떼어주게 된다. 손상은 한참 뒤에 드러난다.
     */
    void free(int address);

    /** 전체 크기. */
    int capacity();

    /** 지금 나가 있는 바이트. 요청한 크기가 아니라 실제로 떼어준 크기다. */
    int usedBytes();

    /** 남은 바이트의 총합. */
    int freeBytes();

    /** 남은 것 중 연속된 가장 큰 덩어리. 이 값이 실제로 떼어줄 수 있는 최대치다. */
    int largestFreeBlock();

    /** 남은 덩어리의 개수. 늘어난다는 것은 잘게 부서지고 있다는 뜻이다. */
    int freeBlockCount();

    /**
     * 요청한 것보다 더 떼어준 바이트의 합. 내부 단편화다.
     *
     * 33 바이트를 달라는데 64 바이트를 떼어주면 31 바이트가 여기 쌓인다.
     * 쓰이지도 않고 돌려주지도 못하는 공간이라 어떤 자에도 안 잡힌다.
     */
    int wastedBytes();
}
