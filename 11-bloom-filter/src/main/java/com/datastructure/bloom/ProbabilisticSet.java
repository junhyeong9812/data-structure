package com.datastructure.bloom;

/**
 * **틀릴 수도 있는** 집합.
 *
 * 지금까지 만든 것들은 전부 정확했다. 있으면 있다고 하고 없으면 없다고 했다.
 * 여기서는 그 정확성을 **일부러 판다.** 대가로 메모리를 수십 배 줄인다.
 *
 * 거래의 모양이 비대칭이라는 점이 중요하다.
 *
 *   mightContain 이 false -> **확실히 없다.** 오답이 아예 불가능하다
 *   mightContain 이 true  -> 아마 있다. **없는데 있다고 할 수 있다**
 *
 * 이 비대칭이 쓸모의 전부다.
 * "없다"가 확실하니까 **비싼 조회를 건너뛰는 앞단 필터**로 쓸 수 있다.
 * 블룸 필터가 false 라고 하면 디스크를 안 읽어도 되고, true 라고 하면 읽어서 확인하면 된다.
 * 틀려도 한 번 더 읽을 뿐 답이 틀리지는 않는다.
 *
 * (실제 쓰임: 카산드라/HBase 의 SSTable 조회, 크롬의 악성 URL 목록,
 *  CDN 캐시의 "한 번만 요청된 것은 캐시하지 않기")
 *
 * 10번 LRU 캐시에서 **일부러 잊어서** 메모리를 한정했다면
 * 여기서는 **일부러 헷갈려서** 메모리를 한정한다.
 *
 * | | 정확한 집합(HashSet) | 블룸 필터 |
 * |---|---|---|
 * | 원소 100만 개 저장 | 수십 MB (원소 자체를 담는다) | **약 1.2MB** (1% 오탐 기준) |
 * | 원소를 꺼내기 | 된다 | **안 된다** - 담은 적이 없다 |
 * | 삭제 | 된다 | **안 된다** (CountingBloomFilter 가 푼다) |
 * | 오답 | 없다 | 오탐만 있다. 누락은 없다 |
 *
 * 구현이 셋이다.
 *
 *   BloomFilter          비트 배열 하나. 기본형
 *   CountingBloomFilter  비트 대신 계수기. 삭제가 된다. 메모리 8배
 *   ScalableBloomFilter  용량을 모를 때. 차면 새 필터를 잇는다
 *
 * 이 인터페이스에는 TODO 가 없다. 계약은 주어지는 것이다.
 */
public interface ProbabilisticSet<T> {

    /** 넣는다. 같은 원소를 두 번 넣어도 비트는 그대로다(계수기형은 다르다). */
    void add(T item);

    /**
     * **false 면 확실히 없다. true 면 아마 있다.**
     *
     * 이 한 줄이 이 자료구조의 계약 전부다.
     */
    boolean mightContain(T item);

    /** add 를 부른 횟수. 서로 다른 원소 수가 아니다 - 블룸 필터는 그걸 알 방법이 없다. */
    long insertedCount();

    /** 실제로 쓰는 비트 수. 이 값이 작다는 것이 존재 이유다. */
    long bitSize();

    /**
     * 지금까지 넣은 개수 기준으로 계산한 **예상** 오탐률.
     *
     * 실측이 아니라 공식이다. 넣을수록 올라간다.
     */
    double expectedFalsePositiveRate();

    void clear();
}
