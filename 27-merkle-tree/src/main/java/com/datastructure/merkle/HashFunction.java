package com.datastructure.merkle;

/**
 * 바이트 열을 고정 길이 요약으로 바꾸는 함수.
 *
 * <h2>왜 인터페이스로 빼는가</h2>
 *
 * 머클 트리의 모든 보장은 "해시 충돌을 못 찾는다"는 가정 하나 위에 서 있다.
 * 가정이라면 깨보여야 한다. 그래서 갈아끼울 수 있게 만든다.
 *
 * Sha256Hash 로 돌리면 정직한 트리가 되고, ToyHash 로 돌리면 같은 코드가
 * 서로 다른 파일에 같은 뿌리를 준다. 코드는 그대로인데 보장만 사라진다.
 * 11번에서 블룸 필터의 오탐률이 해시 품질에 달려 있던 것과 같은 자리인데,
 * 거기서는 성능이 나빠졌고 여기서는 정확성이 사라진다.
 *
 * 이 인터페이스에는 TODO 가 없다. 계약은 주어지는 것이다.
 */
@FunctionalInterface
public interface HashFunction {

    /**
     * data 의 요약을 준다. 같은 입력이면 언제나 같은 출력이어야 하고,
     * 출력 길이는 입력과 무관하게 일정해야 한다.
     *
     * 반환한 배열은 호출자의 것이다. 내부 버퍼를 그대로 돌려주면 안 된다.
     * data 가 null 이면 IllegalArgumentException.
     */
    byte[] hash(byte[] data);
}
