package com.datastructure.skiplist;

import java.util.List;

/**
 * 정렬을 유지하는 맵. 06번 SortedMap 과 같은 계약이다.
 *
 * 06번에서 이 계약을 이진 탐색 트리로 구현했다. 그리고 한계를 봤다.
 * **정렬된 순서로 넣으면 높이가 n 이 되어 연결 리스트가 됐다.**
 *
 * 그걸 고치는 길이 둘이다.
 *
 *   회전으로 강제로 균형을 맞춘다   -> 16번 레드블랙 트리
 *   **동전을 던져 확률로 맞춘다**   -> 여기
 *
 * 스킵 리스트는 트리가 아니다. **정렬된 연결 리스트를 여러 층 쌓은 것**이다.
 * 아래층은 전부를 잇고, 위층은 일부만 건너뛰며 잇는다.
 *
 *   레벨 3:  head ------------------------> 9
 *   레벨 2:  head ------> 4 -------------> 9
 *   레벨 1:  head -> 2 -> 4 -> 6 -------> 9
 *   레벨 0:  head -> 2 -> 4 -> 6 -> 7 -> 9
 *
 * 찾을 때는 맨 위에서 시작해 "다음이 목표보다 크면 한 층 내려간다"를 반복한다.
 * 위층이 크게 건너뛰므로 이진 탐색과 같은 모양이 된다.
 *
 * **어느 노드를 몇 층까지 올릴지는 동전으로 정한다.** 앞면이 나오면 한 층 더.
 * 그래서 절반이 레벨 1, 4분의 1이 레벨 2, ... 기대 높이가 log n 이다.
 *
 * | | BST(06) | 스킵 리스트 |
 * |---|---|---|
 * | 평균 조회 | O(log n) | O(log n) |
 * | **정렬 입력** | **O(n)** 무너진다 | O(log n) 상관없다 |
 * | 최악 | O(n) | O(n) - 확률이 아주 낮다 |
 * | 균형 유지 코드 | 회전(복잡) | **없다** |
 * | 동시성 | 회전이 넓은 범위를 잠근다 | **국소적이라 쉽다** |
 *
 * 마지막 두 줄이 실무에서 쓰이는 이유다.
 * 레디스의 sorted set, 레벨DB/RocksDB 의 memtable, 자바의 ConcurrentSkipListMap 이 이것이다.
 *
 * **무작위성이 자료가 아니라 구조에 있다는 점**이 중요하다.
 * 06번 BST 는 입력이 나쁘면 무너졌다. 여기서는 입력이 무엇이든 상관없다.
 * 나쁜 입력이라는 것이 존재하지 않는다. 나쁜 **동전 운**이 있을 뿐이고, 그건 아주 드물다.
 *
 * 이 인터페이스에는 TODO 가 없다. 계약은 주어지는 것이다.
 */
public interface OrderedMap<K extends Comparable<K>, V> {

    /** 넣는다. 이미 있으면 값을 갈고 옛 값을 준다. 없었으면 null. */
    V put(K key, V value);

    V get(K key);

    boolean containsKey(K key);

    /** 지우고 옛 값을 준다. 없었으면 null. */
    V remove(K key);

    int size();

    boolean isEmpty();

    void clear();

    /** 가장 작은 키. 비었으면 null. */
    K firstKey();

    /** 가장 큰 키. 비었으면 null. */
    K lastKey();

    /** key 이하인 것 중 가장 큰 키. 없으면 null. */
    K floorKey(K key);

    /** key 이상인 것 중 가장 작은 키. 없으면 null. */
    K ceilingKey(K key);

    /** 전부, 정렬 순서로. */
    List<K> keys();

    /** from 이상 to 이하인 키를 정렬 순서로. from > to 면 빈 리스트. */
    List<K> keysInRange(K from, K to);
}
