package com.datastructure.btree;

import java.util.List;

/**
 * 정렬을 유지하는 탐색 트리. 06번, 12번과 같은 계약이다.
 *
 * 06번 이진 탐색 트리는 노드마다 **자식이 둘**이었다. 높이가 log2(n) 이다.
 * 100만 개면 20층이고, 조회 한 번에 20번 노드를 읽는다.
 *
 * 메모리에서는 그게 아무 문제가 아니다. **디스크에서는 재앙이다.**
 * 디스크 읽기 한 번이 메모리 읽기의 수만 배라, 20번 읽으면 그게 전부다.
 *
 * 그래서 질문이 바뀐다. **"비교를 줄이자"가 아니라 "읽기 횟수를 줄이자"** 가 된다.
 *
 * 답은 단순하다. **한 번 읽을 때 많이 읽는다.**
 * 어차피 디스크는 블록 단위(4KB, 16KB)로 읽으므로, 노드 하나를 블록 하나에 맞추고
 * 그 안에 키를 수백 개 담는다. 자식도 수백 개가 된다.
 *
 * | | 이진 탐색 트리 | B-트리 (m = 100) |
 * |---|---|---|
 * | 자식 수 | 2 | 최대 100 |
 * | 1억 개의 높이 | 약 27 | **4** |
 * | 노드 하나 | 키 1개 | 키 99개 |
 * | 어디에 사나 | 메모리 | **디스크** |
 *
 * **높이가 27 에서 4 로 준다.** 디스크 읽기 27번이 4번이 된다.
 * 노드 안에서 키 99개를 훑는 비용은 이미 읽어온 메모리 안의 일이라 사실상 공짜다.
 *
 * 이게 모든 데이터베이스 인덱스가 B-트리 계열인 이유다.
 * MySQL InnoDB, PostgreSQL, SQLite, MongoDB 가 전부 B+트리를 쓴다.
 * 파일 시스템(NTFS, ext4, Btrfs)도 마찬가지다.
 *
 * 이 인터페이스에는 TODO 가 없다. 계약은 주어지는 것이다.
 */
public interface SearchTree<K extends Comparable<K>, V> {

    V put(K key, V value);

    V get(K key);

    boolean containsKey(K key);

    V remove(K key);

    int size();

    boolean isEmpty();

    void clear();

    /** 전부, 정렬 순서로. */
    List<K> keys();

    K firstKey();

    K lastKey();

    /** 뿌리에서 잎까지의 층수. 비었으면 1. **디스크 읽기 횟수가 곧 이 값이다.** */
    int height();
}
