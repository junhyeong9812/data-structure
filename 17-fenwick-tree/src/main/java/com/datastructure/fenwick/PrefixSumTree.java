package com.datastructure.fenwick;

/**
 * 구간 합만 하는 자료구조. **13번 세그먼트 트리가 하던 일의 일부를 훨씬 짧은 코드로.**
 *
 * 13번에서 세그먼트 트리는 결합법칙만 있으면 무엇이든 접었다.
 * 합, 최소, 최대, GCD, 행렬 곱. 그 일반성의 값이 코드 길이와 메모리다.
 *
 * 펜윅 트리는 **합만** 한다. 정확히는 **역연산이 있는 연산만** 한다.
 * 그 하나를 포기하면 코드가 열 줄이 되고 메모리가 4분의 1이 된다.
 *
 * | | 세그먼트 트리 (13번) | 펜윅 트리 |
 * |---|---|---|
 * | 결합 함수 | 아무거나 (모노이드) | **역연산이 있어야 한다** |
 * | 최소/최대 | 된다 | **안 된다** |
 * | 메모리 | 4n | **n + 1** |
 * | 조회/갱신 | O(log n) | O(log n) - **상수가 더 작다** |
 * | 구간 갱신 | lazy 로 된다 | 변형이 필요하다 |
 * | 코드 | 수십 줄 | **열 줄** |
 *
 * **왜 역연산이 필요한가.** 구간 합을 이렇게 구하기 때문이다.
 *
 *   rangeSum(l, r) = prefixSum(r) - prefixSum(l-1)
 *
 * 앞쪽을 통째로 구해놓고 **빼서** 가운데를 얻는다.
 * 최소값에는 이 뺄셈이 없다. min(a..r) 과 min(a..l-1) 을 안다고 min(l..r) 을 알 수 없다.
 * 그래서 펜윅 트리로는 구간 최소를 못 한다. 13번이 여전히 필요한 이유다.
 *
 * **"덜 하면 더 싸다"가 이 문제집에서 계속 나온다.**
 * 07번 힙(전체 정렬 대신 부분 순서), 11번 블룸 필터(정확성 대신 메모리),
 * 14번 유니온 파인드(경로 대신 속도). 여기가 네 번째다.
 *
 * 인덱스는 0 부터 size-1 까지다. 안쪽에서는 1 부터 쓴다(그래야 비트 연산이 맞는다).
 *
 * 이 인터페이스에는 TODO 가 없다. 계약은 주어지는 것이다.
 */
public interface PrefixSumTree {

    int size();

    /** index 번째 값에 delta 를 더한다. */
    void add(int index, long delta);

    /** index 번째 값을 value 로 바꾼다. */
    void set(int index, long value);

    /** index 번째의 현재 값. */
    long get(int index);

    /** 0 번부터 index 번까지(양끝 포함)의 합. index 가 -1 이면 0. */
    long prefixSum(int index);

    /** from 번부터 to 번까지(양끝 포함)의 합. from > to 면 0. */
    long rangeSum(int from, int to);
}
