package com.datastructure.depresolve;

import java.util.List;

/**
 * 의존 순서를 정하는 것의 계약.
 *
 * 두 구현이 이 계약을 지킨다. 그런데 이 박스는 앞의 것들과 사정이 다르다.
 *
 * <h2>정답이 하나가 아니다</h2>
 *
 * a 와 b 가 서로 상관없으면 a 를 먼저 해도 되고 b 를 먼저 해도 된다.
 * 둘 다 맞다. 그래서 두 구현의 답을 그냥 비교할 수가 없다.
 *
 * <pre>
 *   칸 알고리즘   진입 차수 0 인 것부터 뽑는다
 *   DFS          후위 순회를 뒤집는다
 *
 *   같은 그래프에서 둘의 답이 다르다. 그리고 둘 다 맞다.
 * </pre>
 *
 * 그래서 검증 방법을 바꾼다. <b>답을 비교하지 않고 성질을 검사한다.</b>
 * "모든 의존이 자기보다 앞에 있는가" 는 답이 무엇이든 물어볼 수 있다.
 * 32번과 33번에서 쓴 두 구현 대조가 여기서는 성립하지 않고, 그 사실 자체가 이 박스의 내용이다.
 *
 * <h2>실패했을 때 말해줄 수 있는 것이 다르다</h2>
 *
 * 순환이 있으면 순서를 정할 수 없다. 그건 둘 다 안다.
 * 그런데 <b>어디가 순환인지</b>는 한쪽만 안다. resolve 가 아니라 cycle 이 이 박스의 본론이다.
 *
 * 이 인터페이스에는 TODO 가 없다.
 */
public interface Resolver {

    /**
     * 의존이 먼저 오도록 늘어놓는다.
     *
     * 순환이 있으면 CycleException 을 던진다. 부분 결과를 주지 않는다.
     * 절반만 설치된 상태가 아무것도 안 한 상태보다 나쁘기 때문이다.
     */
    List<String> resolve();

    /**
     * 순환 하나. 없으면 빈 목록.
     *
     * 있으면 실제로 도는 경로를 준다. 예를 들어 a -&gt; b -&gt; c -&gt; a 이면
     * [a, b, c, a] 처럼 처음과 끝이 같은 목록이다.
     *
     * 구현에 따라 <b>이걸 못 하는 쪽이 있다.</b> 그 경우 무엇을 주는지가 계약의 일부다.
     */
    List<String> cycle();

    /**
     * 동시에 해도 되는 것끼리 묶은 층.
     *
     * 0층은 아무것에도 의존하지 않는 것들이다. n층은 n-1층까지가 끝나야 시작할 수 있다.
     * 층의 개수가 곧 <b>코어를 아무리 늘려도 못 줄이는 시간</b>이다.
     */
    List<List<String>> layers();
}
